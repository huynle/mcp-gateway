// Package connectortest holds the contract test every connector runs in
// its own test package: ContractTest(t, connector) checks the declared
// tool metadata against the connectors contract so a connector cannot
// reach the registry with an unparseable schema, an undeclared
// reconciliation or a missing resource-identity hook.
package connectortest

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"strings"
	"testing"

	"github.com/huynle/mcp-gateway/internal/connectors"
)

// Upper bounds a sane connector stays under; a tool above them is almost
// certainly a typo (bytes instead of KiB, items instead of pages).
const (
	MaxSanePageSize    = 1000
	MaxSaneResultBytes = 16 << 20
)

var identRE = regexp.MustCompile(`^[a-z0-9_-]+$`)

// ContractTest asserts the connector contract on c: a valid app name; tool
// names valid, unique and under the connector's app; every tool with a
// non-empty description, a JSON Schema that parses to an object, a Kind,
// a ResourceIdentity hook that returns a non-nil map for an empty and a
// sample argument set, sane Bounds; every write with an explicit
// Reconciliation kind (none allowed) and a Check for the other kinds;
// Call returning ErrUnknownTool for an unknown name; and RegisterConnector
// succeeding on a fresh registry with "<app>.list_accounts" added.
func ContractTest(t *testing.T, c connectors.Connector) {
	t.Helper()
	app := c.App()
	if !identRE.MatchString(app) {
		t.Errorf("App() = %q: must match %s", app, identRE)
	}
	tools := c.Tools()
	if len(tools) == 0 {
		t.Error("Tools() is empty")
	}
	seen := map[string]bool{}
	for _, tool := range tools {
		t.Run(tool.Name, func(t *testing.T) { checkTool(t, app, tool, seen) })
	}

	ctx := context.Background()
	if _, err := c.Call(ctx, connectors.Call{Tool: app + ".this_tool_does_not_exist", Args: map[string]any{}}); !errors.Is(err, connectors.ErrUnknownTool) {
		t.Errorf("Call(unknown tool) err = %v, want ErrUnknownTool", err)
	}

	reg := connectors.NewRegistry()
	if err := connectors.RegisterConnector(reg, c, connectors.NewStaticAccountSource()); err != nil {
		t.Fatalf("RegisterConnector: %v", err)
	}
	if _, ok := reg.Get(app + "." + connectors.ListAccountsName); !ok {
		t.Errorf("%s.%s missing after RegisterConnector", app, connectors.ListAccountsName)
	}
	if got, want := len(reg.List()), len(tools)+1; got != want {
		t.Errorf("registry has %d tools after RegisterConnector, want %d", got, want)
	}
}

func checkTool(t *testing.T, app string, tool connectors.Tool, seen map[string]bool) {
	t.Helper()
	full := tool.FullName()
	if tool.App != app {
		t.Errorf("%s: App %q != connector app %q", full, tool.App, app)
	}
	if !identRE.MatchString(tool.Name) {
		t.Errorf("%s: name must match %s", full, identRE)
	}
	if tool.Name == connectors.ListAccountsName {
		t.Errorf("%s: %s is generated by RegisterConnector", full, connectors.ListAccountsName)
	}
	if seen[full] {
		t.Errorf("%s: declared twice", full)
	}
	seen[full] = true
	if strings.TrimSpace(tool.Description) == "" {
		t.Errorf("%s: empty description", full)
	}
	checkSchema(t, full, tool.InputSchema)
	switch tool.Kind {
	case connectors.KindRead:
		if tool.Reconcile.Kind != "" {
			t.Errorf("%s: a read declares reconciliation %q", full, tool.Reconcile.Kind)
		}
		if tool.ResultIDs != nil {
			t.Errorf("%s: a read declares ResultIDs (the ledger records writes only)", full)
		}
	case connectors.KindWrite:
		if !tool.Reconcile.Kind.Valid() {
			t.Errorf("%s: write must declare a reconciliation kind (none is allowed but explicit), got %q", full, tool.Reconcile.Kind)
		}
		if tool.Reconcile.Kind != connectors.ReconcileNone && tool.Reconcile.Kind.Valid() && tool.Reconcile.Check == nil {
			t.Errorf("%s: reconciliation %s needs a Check", full, tool.Reconcile.Kind)
		}
		if tool.Reconcile.Kind == connectors.ReconcileNone && tool.Reconcile.Check != nil {
			t.Errorf("%s: reconciliation none with a Check: pick a kind", full)
		}
	default:
		t.Errorf("%s: Kind must be read or write, got %q", full, tool.Kind)
	}
	if tool.ResourceIdentity == nil {
		t.Errorf("%s: ResourceIdentity is nil (return an empty map when there is none)", full)
	} else {
		for _, args := range []map[string]any{nil, {}, sampleArgs(tool.InputSchema)} {
			if id := tool.ResourceIdentity(args); id == nil {
				t.Errorf("%s: ResourceIdentity(%v) returned nil", full, args)
			}
		}
	}
	b := tool.Bounds
	if b.MaxPageSize < 0 || b.MaxPageSize > MaxSanePageSize {
		t.Errorf("%s: MaxPageSize %d out of [0, %d]", full, b.MaxPageSize, MaxSanePageSize)
	}
	if b.MaxResultBytes <= 0 || b.MaxResultBytes > MaxSaneResultBytes {
		t.Errorf("%s: MaxResultBytes %d out of (0, %d]", full, b.MaxResultBytes, MaxSaneResultBytes)
	}
	if tool.NoAccount {
		t.Errorf("%s: NoAccount is reserved for the generated list_accounts tool", full)
	}
}

func checkSchema(t *testing.T, full string, raw json.RawMessage) {
	t.Helper()
	var schema map[string]any
	if err := json.Unmarshal(raw, &schema); err != nil {
		t.Errorf("%s: input schema does not parse: %v", full, err)
		return
	}
	if schema["type"] != "object" {
		t.Errorf("%s: input schema type = %v, want \"object\"", full, schema["type"])
	}
	if props, ok := schema["properties"]; ok {
		pm, ok := props.(map[string]any)
		if !ok {
			t.Errorf("%s: properties is not an object", full)
			return
		}
		for name, p := range pm {
			if _, ok := p.(map[string]any); !ok {
				t.Errorf("%s: property %q is not a schema object", full, name)
			}
			if name == "account" || name == "approval_id" {
				t.Errorf("%s: property %q is gateway-owned; the gateway injects it", full, name)
			}
		}
	}
	if req, ok := schema["required"]; ok {
		list, ok := req.([]any)
		if !ok {
			t.Errorf("%s: required is not an array", full)
		}
		pm, _ := schema["properties"].(map[string]any)
		for _, r := range list {
			if name, _ := r.(string); pm[name] == nil {
				t.Errorf("%s: required property %v is not declared", full, r)
			}
		}
	}
}

// sampleArgs builds one plausible argument per declared property so
// ResourceIdentity is exercised with the types it expects.
func sampleArgs(raw json.RawMessage) map[string]any {
	var schema struct {
		Properties map[string]struct {
			Type string `json:"type"`
		} `json:"properties"`
	}
	_ = json.Unmarshal(raw, &schema)
	args := map[string]any{}
	for name, p := range schema.Properties {
		switch p.Type {
		case "integer", "number":
			args[name] = 1
		case "boolean":
			args[name] = true
		case "array":
			args[name] = []any{}
		case "object":
			args[name] = map[string]any{}
		default:
			args[name] = fmt.Sprintf("sample-%s", name)
		}
	}
	return args
}
